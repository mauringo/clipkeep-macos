import Foundation
import Testing
import CoreGraphics
import CoreText
import AppKit
@testable import ClipboardCore

struct NewFeaturesTests {
    private func withArchive(_ body: (URL) throws -> Void) throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        try body(directory.appendingPathComponent("history.json"))
    }

    @Test func oldArchivesLoadWithoutPinsOrRecognizedText() throws {
        let entry = ClipboardEntry(text: "Original")
        var object = try #require(JSONSerialization.jsonObject(with: JSONEncoder().encode(entry)) as? [String: Any])
        object.removeValue(forKey: "isPinned")
        object.removeValue(forKey: "recognizedText")
        let decoded = try JSONDecoder().decode(ClipboardEntry.self, from: JSONSerialization.data(withJSONObject: object))
        #expect(!decoded.isPinned)
        #expect(decoded.recognizedText == nil)
        #expect(decoded.text == "Original")
    }

    @Test func pinsSurviveEvictionLimitChangesAndReloadButUnpinningReappliesLimit() throws {
        try withArchive { url in
            let repository = try HistoryRepository(archiveURL: url, settings: HistorySettings(maximumEntries: 1))
            let pinned = ClipboardEntry(text: "Keep me")
            try repository.insert(pinned)
            try repository.setPinned(true, id: pinned.id)
            try repository.insert(ClipboardEntry(text: "new"))
            try repository.insert(ClipboardEntry(text: "newest"))
            #expect(repository.entries.compactMap(\.text) == ["newest", "Keep me"])
            try repository.updateSettings(HistorySettings(maximumEntries: 1))
            let restored = try HistoryRepository(archiveURL: url, settings: HistorySettings(maximumEntries: 1))
            #expect(restored.entries.last?.isPinned == true)
            try restored.setPinned(false, id: pinned.id)
            #expect(restored.entries.compactMap(\.text) == ["newest"])
        }
    }

    @Test func metadataUpdatesKeepOriginalImageAndDoNotResurrectDeletedItems() throws {
        try withArchive { url in
            let repository = try HistoryRepository(archiveURL: url)
            let bytes = Data([1, 2, 3])
            let image = ClipboardEntry(pngData: bytes)
            try repository.insert(image)
            try repository.setRecognizedText("Invoice 2048", id: image.id)
            try repository.setPinned(true, id: image.id)
            let restored = try HistoryRepository(archiveURL: url)
            #expect(restored.entries[0].imageData == bytes)
            #expect(restored.entries[0].searchableText == "Invoice 2048")
            #expect(restored.entries[0].hasSameContent(as: image))
            try repository.remove(id: image.id)
            try repository.setRecognizedText("Late result", id: image.id)
            #expect(repository.entries.isEmpty)
        }
    }

    @Test func pinningAndRecognitionRespectSessionOnlyRetention() throws {
        try withArchive { url in
            let settings = HistorySettings(keepAfterRestart: false)
            let repository = try HistoryRepository(archiveURL: url, settings: settings)
            let entry = ClipboardEntry(pngData: Data([1]))
            try repository.insert(entry)
            try repository.setPinned(true, id: entry.id)
            try repository.setRecognizedText("private", id: entry.id)
            #expect(!FileManager.default.fileExists(atPath: url.path))
            #expect(try HistoryRepository(archiveURL: url, settings: settings).entries.isEmpty)
        }
    }

    @Test func capturePolicyRespectsMarkersAndAppExclusionsIndependently() {
        var policy = CapturePreferences(excludedBundleIDs: ["example.secret"])
        #expect(!policy.shouldCapture(types: [], sourceBundleID: "example.secret"))
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            #expect(!policy.shouldCapture(types: ["public.utf8-plain-text", marker], sourceBundleID: nil))
        }
        #expect(policy.shouldCapture(types: ["public.utf8-plain-text"], sourceBundleID: nil))
        policy.ignoreSensitiveContent = false
        #expect(policy.shouldCapture(types: ["org.nspasteboard.ConcealedType"], sourceBundleID: nil))
        #expect(!policy.shouldCapture(types: [], sourceBundleID: "example.secret"))
    }

    @Test func capturePreferencesPersistAndDefaultToLocalRecognitionAndPrivacy() throws {
        let suite = "test-" + UUID().uuidString
        let defaults = try #require(UserDefaults(suiteName: suite))
        defer { defaults.removePersistentDomain(forName: suite) }
        #expect(CapturePreferences.load(from: defaults) == CapturePreferences())
        let preferences = CapturePreferences(excludedBundleIDs: ["example.app"], ignoreSensitiveContent: false, recognizeTextInImages: false)
        preferences.save(to: defaults)
        #expect(CapturePreferences.load(from: defaults) == preferences)
    }

    @Test func visionRecognizesTextFromAnImageOnDevice() throws {
        let context = try #require(CGContext(data: nil, width: 600, height: 120, bitsPerComponent: 8,
            bytesPerRow: 0, space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(CGColor(gray: 1, alpha: 1))
        context.fill(CGRect(x: 0, y: 0, width: 600, height: 120))
        context.textPosition = CGPoint(x: 20, y: 40)
        let text = NSAttributedString(string: "CLIPBOARD 2048", attributes: [
            NSAttributedString.Key(kCTFontAttributeName as String): CTFontCreateWithName("Helvetica" as CFString, 48, nil),
            NSAttributedString.Key(kCTForegroundColorAttributeName as String): CGColor(gray: 0, alpha: 1)])
        CTLineDraw(CTLineCreateWithAttributedString(text), context)
        let image = try #require(context.makeImage())
        let png = try #require(NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]))
        let result = try ImageTextRecognition.recognize(png)
        #expect(result.contains("CLIPBOARD"))
        #expect(result.contains("2048"))
    }
}
