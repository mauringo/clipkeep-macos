import Foundation

public struct CapturePreferences: Equatable {
    public var excludedBundleIDs: Set<String>
    public var ignoreSensitiveContent: Bool
    public var recognizeTextInImages: Bool

    public init(excludedBundleIDs: Set<String> = [], ignoreSensitiveContent: Bool = true,
                recognizeTextInImages: Bool = true) {
        self.excludedBundleIDs = excludedBundleIDs
        self.ignoreSensitiveContent = ignoreSensitiveContent
        self.recognizeTextInImages = recognizeTextInImages
    }

    public static func load(from defaults: UserDefaults = .standard) -> CapturePreferences {
        CapturePreferences(excludedBundleIDs: Set(defaults.stringArray(forKey: "excludedCaptureApps") ?? []),
            ignoreSensitiveContent: defaults.object(forKey: "ignoreSensitiveClipboard") as? Bool ?? true,
            recognizeTextInImages: defaults.object(forKey: "recognizeClipboardImages") as? Bool ?? true)
    }

    public func save(to defaults: UserDefaults = .standard) {
        defaults.set(excludedBundleIDs.sorted(), forKey: "excludedCaptureApps")
        defaults.set(ignoreSensitiveContent, forKey: "ignoreSensitiveClipboard")
        defaults.set(recognizeTextInImages, forKey: "recognizeClipboardImages")
    }

    public func shouldCapture(types: Set<String>, sourceBundleID: String?) -> Bool {
        if let sourceBundleID, excludedBundleIDs.contains(sourceBundleID) { return false }
        let ignoredTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        return !ignoreSensitiveContent || types.isDisjoint(with: ignoredTypes)
    }
}
